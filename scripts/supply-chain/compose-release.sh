#!/usr/bin/env bash
# Run the local stack from a verified, signed release instead of local builds (docs/supply-chain.md).
#
#   scripts/supply-chain/compose-release.sh --release keelson-release.env [--signing-env FILE] [--out FILE]
#   docker compose build pg-core      # once: pg-core is not a release image (--no-build needs it locally)
#   docker compose -f compose.yaml -f compose.release.yaml up -d --no-build
#
# Verifies the release file (Sigstore bundle keelson-release.env.sigstore.json next to it) and every
# image it maps to a compose service (signature by release.yml with the release's git_sha, SBOM and
# provenance attestations), then writes the git-ignored override compose.release.yaml: each built
# service gets `build: !reset null` and `image: <ghcr ref@sha256>`. Nothing is written when any check
# fails. The stack then runs CI-built, verified images: no local BuildKit cache grows on the disk.
# pg-core is not a release image (Cloud SQL replaces it on Cloud Run) and keeps its local build: build it
# once (`docker compose build pg-core`), or `up --no-build` stops at the missing keelson-pg-core image.
# Exit status: 0, 1 = verification failed (nothing written), 2 = usage/policy error.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=scripts/supply-chain/lib/verify.sh
source "$ROOT/scripts/supply-chain/lib/verify.sh"
usage() { sed -n '2,/^set -uo/p' "${BASH_SOURCE[0]}" | sed '$d' | sed 's/^# \{0,1\}//'; }
die() { printf 'compose-release.sh: %s\n' "$*" >&2; exit 2; }

# compose service -> RELEASE_IMAGE_<KEY> (the base images, not the Cloud Run domain overlays).
# scripts/supply-chain/check_pins.py (P9) checks this table against compose.yaml and images.json.
COMPOSE_RELEASE_MAP=(
  bootstrap:ENGINE engine-api:ENGINE engine-worker:ENGINE optimizer:OPTIMIZER
  merxa-api:MERXA_API merxa-web:MERXA_WEB keelson-web:KEELSON_WEB
  signal-hub-bootstrap:SIGNAL_HUB signal-hub-api:SIGNAL_HUB signal-hub-poller:SIGNAL_HUB
)

RELEASE=""; SIGNING_ENV="$ROOT/infra/supply-chain/signing.env"; OUT="$ROOT/compose.release.yaml"
while [ $# -gt 0 ]; do
  case "$1" in
    --release) RELEASE="${2:?--release needs a file}"; shift 2 ;;
    --signing-env) SIGNING_ENV="${2:?--signing-env needs a file}"; shift 2 ;;
    --out) OUT="${2:?--out needs a file}"; shift 2 ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown argument $1 (see --help)" ;;
  esac
done
[ -n "$RELEASE" ] || die "--release FILE is required"
sc_load_signing_env "$SIGNING_ENV" || die "$SC_ERROR"
[ "$SC_SIGNER_MODE" = keyless ] || printf 'compose-release.sh: WARNING: SIGNER_MODE=%s (test key)\n' "$SC_SIGNER_MODE" >&2

sc_verify_release "$RELEASE" || { printf 'compose-release.sh: refusing %s: %s\n' "$RELEASE" "$SC_ERROR" >&2; exit 1; }
declare -A verified=()
body=""
for pair in "${COMPOSE_RELEASE_MAP[@]}"; do
  svc="${pair%%:*}"; key="RELEASE_IMAGE_${pair#*:}"
  ref="${SC_RELEASE[$key]:-}"
  [ -n "$ref" ] || { printf 'compose-release.sh: %s has no %s\n' "$RELEASE" "$key" >&2; exit 1; }
  if [ -z "${verified[$ref]:-}" ]; then
    sc_verify_ref "$ref" "git_sha=${SC_RELEASE[RELEASE_GIT_SHA]}" ||
      { printf 'compose-release.sh: refusing unverified image %s: %s\n' "$ref" "$SC_ERROR" >&2; exit 1; }
    verified[$ref]=1
  fi
  body+="  ${svc}:"$'\n'"    build: !reset null"$'\n'"    image: ${ref}"$'\n'
done
tmp="$OUT.tmp.$$"
if ! {
  printf '# Generated by scripts/supply-chain/compose-release.sh - do not edit, do not commit.\n'
  printf '# Release %s (git %s, run %s), verified against %s.\n' "${SC_RELEASE[RELEASE_REF]}" \
    "${SC_RELEASE[RELEASE_GIT_SHA]}" "${SC_RELEASE[RELEASE_RUN_ID]}" "$(basename "$SIGNING_ENV")"
  printf '# docker compose build pg-core   (once; not a release image)\n'
  printf '# docker compose -f compose.yaml -f compose.release.yaml up -d --no-build\n'
  printf 'services:\n%s' "$body"
} >"$tmp" || ! mv "$tmp" "$OUT"; then
  rm -f "$tmp"
  die "cannot write $OUT"
fi
printf 'compose-release.sh: wrote %s (%d services, %d verified images)\n' "$OUT" "${#COMPOSE_RELEASE_MAP[@]}" "${#verified[@]}" >&2
