#!/usr/bin/env node
// Converts packages/contracts-ts/schemas/*.schema.json (listed in schemas/index.json, generated
// from the Pydantic models in packages/contracts-py) into Zod 4 modules under src/generated/.
//
//   node scripts/gen-zod.mjs          write src/generated/*.ts
//   node scripts/gen-zod.mjs --check  exit 1 when the committed output is stale (CI / build)
//
// The output is committed so builds are reproducible without running the generator.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const schemaDir = path.join(pkgRoot, "schemas");
const outDir = path.join(pkgRoot, "src", "generated");

/** "block.kpi_strip.v1.props" -> "blockKpiStripV1Props" */
export function camel(name) {
  return name.replace(/[.\-_@]+(\w)/g, (_, c) => c.toUpperCase());
}

/** "block.kpi_strip.v1.props" -> "block-kpi_strip-v1-props" (module file stem) */
export function fileStem(name) {
  return name.replace(/\./g, "-");
}

const HEADER = (file, source) =>
  [
    "// @generated by packages/contracts-ts/scripts/gen-zod.mjs — DO NOT EDIT.",
    `// Source: packages/contracts-ts/schemas/${file}${source ? ` (${source})` : ""}`,
    "// Regenerate: pnpm --filter @keelson/contracts generate",
    "",
  ].join("\n");

/**
 * json-schema-to-zod 2.8.1 predates 2020-12 `prefixItems` (it would emit `z.any()`), but it
 * turns the draft-07 tuple form `items: [...]` into `z.tuple([...])`. Rewrite closed tuples
 * (`prefixItems` without extra items) into that form; the schema files stay 2020-12.
 */
export function legacyTuples(node) {
  if (Array.isArray(node)) return node.map(legacyTuples);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) out[key] = legacyTuples(value);
  if (Array.isArray(out.prefixItems)) {
    if (out.items !== undefined && out.items !== false) {
      throw new Error("prefixItems with additional items is not supported by the generator");
    }
    out.items = out.prefixItems;
    delete out.prefixItems;
  }
  return out;
}

/** Build every generated module in memory: Map<relative file name, contents>. */
export function generate() {
  const index = JSON.parse(fs.readFileSync(path.join(schemaDir, "index.json"), "utf8"));
  const entries = [...index.schemas].sort((a, b) => a.name.localeCompare(b.name));
  const files = new Map();
  const exportLines = [];
  for (const { name, file, source } of entries) {
    const schema = legacyTuples(JSON.parse(fs.readFileSync(path.join(schemaDir, file), "utf8")));
    const base = camel(name);
    const constName = `${base}Schema`;
    const typeName = base[0].toUpperCase() + base.slice(1);
    let code = jsonSchemaToZod(schema, {
      name: constName,
      module: "esm",
      type: typeName,
      zodVersion: 4,
      withoutDescribes: true,
    });
    if (/\bz\.any\(\)/.test(code) && !/"additionalProperties":true/.test(JSON.stringify(schema))) {
      throw new Error(`${file}: converter produced z.any() — schema must be self-contained`);
    }
    code = code.replace(/\r\n/g, "\n").trimEnd() + "\n";
    const stem = fileStem(name);
    files.set(`${stem}.ts`, HEADER(file, source) + code);
    exportLines.push(`export { ${constName}, type ${typeName} } from "./${stem}";`);
  }
  files.set(
    "index.ts",
    HEADER("index.json", "all schemas") + exportLines.join("\n") + "\n",
  );
  return files;
}

/** Line-ending-insensitive comparison (a Windows `core.autocrlf` checkout is not "stale"). */
export function sameText(a, b) {
  return a !== null && b !== null && a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
}

function main() {
  const check = process.argv.includes("--check");
  const files = generate();
  const stale = [];
  const existing = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((f) => f.endsWith(".ts")) : [];
  for (const [rel, contents] of files) {
    const target = path.join(outDir, rel);
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
    if (sameText(current, contents)) continue;
    stale.push(rel);
    if (!check) {
      fs.mkdirSync(outDir, { recursive: true });
      fs.writeFileSync(target, contents);
    }
  }
  const orphans = existing.filter((f) => !files.has(f));
  if (check) {
    if (stale.length || orphans.length) {
      console.error(
        `@keelson/contracts: generated Zod is stale (${[...stale, ...orphans].join(", ")}). ` +
          "Run `pnpm --filter @keelson/contracts generate`.",
      );
      process.exit(1);
    }
    console.log(`@keelson/contracts: ${files.size} generated modules up to date`);
    return;
  }
  for (const orphan of orphans) fs.rmSync(path.join(outDir, orphan));
  console.log(
    `@keelson/contracts: wrote ${stale.length} of ${files.size} modules` +
      (orphans.length ? `, removed ${orphans.length} stale` : ""),
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
