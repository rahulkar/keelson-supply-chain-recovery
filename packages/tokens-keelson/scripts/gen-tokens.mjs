#!/usr/bin/env node
// Generates src/tokens.css and src/generated/hex.ts from src/palette.ts (the single source of truth).
//
//   node scripts/gen-tokens.mjs          write outputs
//   node scripts/gen-tokens.mjs --check  exit 1 when committed outputs are stale
//
// src/palette.ts is imported directly (Node >= 22.18 / 24 strips erasable TypeScript syntax).
// culori converts OKLCH to gamut-mapped sRGB hex for browsers without OKLCH and for canvas
// libraries (ECharts, deck.gl) that do not parse oklch().
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clampChroma, formatHex, formatHex8, parse } from "culori";
import {
  colorRoles,
  durations,
  easings,
  layout,
  palette,
  radii,
  shadows,
  spacingUnit,
  typeScale,
} from "../src/palette.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.resolve(here, "..", "src");

/** OKLCH (optionally with alpha) → sRGB hex, chroma-clamped into gamut. */
export function toHex(value) {
  const parsed = parse(value);
  if (!parsed) throw new Error(`Unparseable colour: ${value}`);
  const inGamut = clampChroma(parsed, "oklch");
  return parsed.alpha !== undefined && parsed.alpha < 1 ? formatHex8(inGamut) : formatHex(inGamut);
}

const DARK_SHADOWS = {
  sm: "0 1px 2px 0 oklch(0 0 0 / 0.3)",
  md: "0 2px 8px -2px oklch(0 0 0 / 0.4), 0 1px 2px 0 oklch(0 0 0 / 0.3)",
  lg: "0 12px 32px -8px oklch(0 0 0 / 0.55), 0 2px 6px -2px oklch(0 0 0 / 0.35)",
  composer: "0 4px 20px -6px oklch(0 0 0 / 0.5), 0 1px 3px 0 oklch(0 0 0 / 0.3)",
};

function colorBlock(theme, format) {
  return colorRoles.map((role) => `  --k-${role}: ${format(palette[theme][role])};`).join("\n");
}

function staticBlock() {
  const lines = [];
  for (const [k, v] of Object.entries(radii)) lines.push(`  --k-radius-${k}: ${v}px;`);
  for (const [k, t] of Object.entries(typeScale)) {
    lines.push(`  --k-text-${k}: ${t.size / 16}rem;`);
    lines.push(`  --k-text-${k}-line: ${t.line / 16}rem;`);
    lines.push(`  --k-text-${k}-weight: ${t.weight};`);
    lines.push(`  --k-text-${k}-tracking: ${t.tracking};`);
  }
  lines.push(`  --k-space: ${spacingUnit / 16}rem;`);
  for (const [k, v] of Object.entries(durations)) lines.push(`  --k-duration-${k}: ${v}ms;`);
  for (const [k, v] of Object.entries(easings)) lines.push(`  --k-ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(shadows)) lines.push(`  --k-shadow-${k}: ${v};`);
  lines.push(`  --k-chat-max: ${layout.chatMaxWidth}px;`);
  lines.push(`  --k-canvas-width: ${layout.canvasWidthPct}%;`);
  lines.push(`  --k-header-height: ${layout.headerHeight}px;`);
  return lines.join("\n");
}

export function renderCss() {
  const darkShadows = Object.entries(DARK_SHADOWS)
    .map(([k, v]) => `  --k-shadow-${k}: ${v};`)
    .join("\n");
  return `/* @generated by packages/tokens-keelson/scripts/gen-tokens.mjs from src/palette.ts — DO NOT EDIT. */
/* Keelson design tokens: OKLCH colours (light + [data-theme=dark]), radii, type, motion, elevation. */

:root,
[data-theme="light"] {
  color-scheme: light;
${colorBlock("light", (v) => v)}
${staticBlock()}
}

[data-theme="dark"] {
  color-scheme: dark;
${colorBlock("dark", (v) => v)}
${darkShadows}
}

/* sRGB fallbacks for engines without oklch() support. */
@supports not (color: oklch(0 0 0)) {
  :root,
  [data-theme="light"] {
${colorBlock("light", toHex).replace(/^ {2}/gm, "    ")}
  }

  [data-theme="dark"] {
${colorBlock("dark", toHex).replace(/^ {2}/gm, "    ")}
  }
}
`;
}

export function renderHexTs() {
  const theme = (name) =>
    colorRoles.map((role) => `    ${JSON.stringify(role)}: ${JSON.stringify(toHex(palette[name][role]))},`).join("\n");
  return `// @generated by packages/tokens-keelson/scripts/gen-tokens.mjs from src/palette.ts — DO NOT EDIT.
// sRGB hex fallbacks (gamut-mapped with culori) for canvas libraries that cannot parse oklch().
export const hex = {
  light: {
${theme("light")}
  },
  dark: {
${theme("dark")}
  },
} as const;
`;
}

export function outputs() {
  return new Map([
    [path.join(srcDir, "tokens.css"), renderCss()],
    [path.join(srcDir, "generated", "hex.ts"), renderHexTs()],
  ]);
}

/** Line-ending-insensitive comparison (a Windows `core.autocrlf` checkout is not "stale"). */
export function sameText(a, b) {
  return a !== null && b !== null && a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
}

function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [file, contents] of outputs()) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (sameText(current, contents)) continue;
    stale.push(path.relative(path.resolve(srcDir, ".."), file));
    if (!check) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, contents);
    }
  }
  if (check && stale.length) {
    console.error(`@keelson/tokens: stale generated files (${stale.join(", ")}). Run \`pnpm --filter @keelson/tokens generate\`.`);
    process.exit(1);
  }
  console.log(check ? "@keelson/tokens: generated files up to date" : `@keelson/tokens: wrote ${stale.length} file(s)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
